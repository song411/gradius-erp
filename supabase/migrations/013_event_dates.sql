-- 행사의 실제 운영일
--
-- '09월 18일,19일 / 09월 25일,26일 / 10월 2일,3일 / 10월 9일,10일 / 10월 16일,17일'
-- 처럼 띄엄띄엄 도는 행사가 있다. 지금까지 날짜 칸은 event_start / event_end 두 개뿐이라
-- 9/18 ~ 10/17 로 넣을 수밖에 없었고, 실제로는 10일인 행사가 30일짜리가 됐다.
--
-- 그 결과 운영 캘린더 막대가 30일을 덮고, 구글 캘린더도 30일 통 블록이 되며,
-- 근무일 미지정 인력이 '전체기간 투입'으로 30일 근무로 계산돼 중복배정 오탐이 쏟아졌다.
-- (실제 홍천 정기 행사: 견적 일수는 10일로 정확한데 event_start~end 만 30일이었다)
--
-- event_start / event_end 는 그대로 둔다. 기존 화면 수십 곳이 그 두 값을 읽고 있고,
-- 이 컬럼은 비어 있을 때 예전과 완전히 같은 동작을 해야 하기 때문이다.
--
-- ★ NULL 이면 'event_start~event_end 전체가 운영일' 이라는 기존 동작을 그대로 뜻한다.
--   전체 행사의 10% 도 안 되는 정기 행사에만 채운다.

ALTER TABLE inquiries ADD COLUMN IF NOT EXISTS event_dates DATE[];
